import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const cssFiles = [
  "src/styles/base.css",
  "src/styles/header.css",
  "src/index.css",
  "src/styles/info-pages.css",
  "src/styles/constructor.css",
];

const sourceExtensions = new Set([".ts", ".tsx", ".js", ".jsx", ".html", ".mjs", ".cjs"]);
const sourceDirs = ["src", "api", "scripts"];

function read(filePath) {
  return fs.readFileSync(path.join(root, filePath), "utf8");
}

function walk(dir) {
  const fullDir = path.join(root, dir);
  if (!fs.existsSync(fullDir)) return [];

  return fs.readdirSync(fullDir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(fullDir, entry.name);
    const rel = path.relative(root, full);

    if (entry.isDirectory()) {
      if (["node_modules", "dist", ".vite", ".cache"].includes(entry.name)) return [];
      return walk(rel);
    }

    if (!sourceExtensions.has(path.extname(entry.name))) return [];
    return [rel];
  });
}

function extractClasses(css) {
  const classNames = new Set();
  const regex = /\.(-?[_a-zA-Z]+[_a-zA-Z0-9-]*)/g;
  let match;

  while ((match = regex.exec(css)) !== null) {
    const className = match[1];
    if (!className.startsWith("rzm-")) continue;
    classNames.add(className);
  }

  return [...classNames].sort();
}

function makePrefix(className) {
  const parts = className.split("-");
  return parts.slice(0, Math.min(parts.length, 3)).join("-");
}

function findPotentialLegacySelectors(classes, sourceText) {
  return classes.filter((className) => {
    const prefix = makePrefix(className);
    const exactFound = sourceText.includes(className);
    const likelyDynamic = sourceText.includes(prefix);
    return !exactFound && !likelyDynamic;
  });
}

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  return `${(bytes / 1024).toFixed(2)} KB`;
}

const sourceFiles = sourceDirs.flatMap(walk);
const sourceText = sourceFiles.map((file) => read(file)).join("\n");

const inventory = cssFiles.map((file) => {
  const full = path.join(root, file);
  const css = fs.existsSync(full) ? read(file) : "";
  const classes = extractClasses(css);
  const potentialLegacySelectors = findPotentialLegacySelectors(classes, sourceText);

  return {
    file,
    bytes: Buffer.byteLength(css),
    size: formatBytes(Buffer.byteLength(css)),
    lineCount: css.split(/\r?\n/).length,
    classCount: classes.length,
    potentialLegacyCount: potentialLegacySelectors.length,
    potentialLegacySelectors: potentialLegacySelectors.slice(0, 80),
  };
});

const totalBytes = inventory.reduce((sum, item) => sum + item.bytes, 0);
const totalClasses = inventory.reduce((sum, item) => sum + item.classCount, 0);

const reportLines = [
  "# CSS inventory report",
  "",
  "Generated by `npm run report:css-inventory`.",
  "",
  "## Summary",
  "",
  `- Total CSS size: ${formatBytes(totalBytes)} (${totalBytes} bytes)`,
  `- Total detected rzm-* classes: ${totalClasses}`,
  "",
  "## Files",
  "",
  "| File | Size | Lines | rzm-* classes | Potential legacy selectors |",
  "|---|---:|---:|---:|---:|",
  ...inventory.map((item) => `| ${item.file} | ${item.size} | ${item.lineCount} | ${item.classCount} | ${item.potentialLegacyCount} |`),
  "",
  "## Potential legacy selectors",
  "",
  "This section is intentionally conservative. It does not delete anything. A selector is listed only when the exact class and a short prefix are not found in source files. Dynamic HTML strings and future code generation can still produce false positives.",
  "",
  ...inventory.flatMap((item) => [
    `### ${item.file}`,
    "",
    item.potentialLegacySelectors.length
      ? item.potentialLegacySelectors.map((selector) => `- .${selector}`).join("\n")
      : "No candidates found.",
    "",
  ]),
];

const outputDir = path.join(root, "docs/audit");
fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(path.join(outputDir, "css-inventory-report.md"), reportLines.join("\n"), "utf8");

console.log("CSS inventory complete");
console.log(`Total CSS size: ${formatBytes(totalBytes)}`);
for (const item of inventory) {
  console.log(`${item.file}: ${item.size}, ${item.classCount} classes, ${item.potentialLegacyCount} potential legacy`);
}
