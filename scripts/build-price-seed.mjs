import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const sourcePath = path.join(root, 'src/pricing/seed/price-items.json')
const outDir = path.join(root, 'db/seed')
const jsonlPath = path.join(outDir, 'price-items.jsonl')
const sqlPath = path.join(outDir, 'price-items.sql')

const items = JSON.parse(fs.readFileSync(sourcePath, 'utf8'))

fs.mkdirSync(outDir, { recursive: true })

function snake(value) {
  return value.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`)
}

function toDbRow(item) {
  return {
    item_type: item.itemType,
    producer: item.producer ?? null,
    brand: item.brand ?? null,
    collection: item.collection ?? null,
    article: item.article ?? null,
    name: item.name,
    decor_name: item.decorName ?? null,
    texture: item.texture ?? null,
    category: item.category ?? null,
    thickness_mm: item.thicknessMm ?? null,
    width_mm: item.widthMm ?? null,
    length_mm: item.lengthMm ?? null,
    unit: item.unit,
    source_price: item.sourcePrice,
    markup_multiplier: item.markupMultiplier,
    currency: 'RUB',
    vat_included: true,
    availability_status: item.availabilityStatus ?? null,
    source_sheet: item.sourceSheet,
    source_row: item.sourceRow,
    source_note: item.sourceNote ?? null,
    is_active: true,
  }
}

function sqlString(value) {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'number') return String(value)
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  return `'${String(value).replaceAll("'", "''")}'`
}

const rows = items.map(toDbRow)
fs.writeFileSync(jsonlPath, rows.map((row) => JSON.stringify(row)).join('\n') + '\n')

const columns = Object.keys(rows[0])
const values = rows
  .map((row) => `(${columns.map((column) => sqlString(row[column])).join(', ')})`)
  .join(',\n')

const sql = `-- Auto-generated by scripts/build-price-seed.mjs
-- Source: src/pricing/seed/price-items.json
-- Rule: retail_price is generated in DB as source_price * markup_multiplier.

insert into public.price_items (
  ${columns.join(',\n  ')}
)
values
${values}
on conflict do nothing;
`

fs.writeFileSync(sqlPath, sql)

const summary = rows.reduce((acc, row) => {
  acc[row.item_type] = (acc[row.item_type] ?? 0) + 1
  return acc
}, {})

console.log(JSON.stringify({
  ok: true,
  source: path.relative(root, sourcePath),
  jsonl: path.relative(root, jsonlPath),
  sql: path.relative(root, sqlPath),
  count: rows.length,
  summary,
}, null, 2))
