import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const scanDirs = [
  "src/static-pages",
  "src/components",
  "src/pages",
].filter((dir) => fs.existsSync(path.join(root, dir)));

const maxSoftLines = 220;
const maxSoftBytes = 9000;

function walk(dir) {
  const fullDir = path.join(root, dir);
  if (!fs.existsSync(fullDir)) return [];

  return fs.readdirSync(fullDir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(fullDir, entry.name);
    const rel = path.relative(root, full);

    if (entry.isDirectory()) {
      if (["node_modules", "dist", ".vite", ".cache"].includes(entry.name)) return [];
      return walk(rel);
    }

    if (!entry.name.endsWith(".tsx")) return [];
    return [rel];
  });
}

function detectExports(text) {
  const matches = [...text.matchAll(/export\s+(?:default\s+)?function\s+([A-Z][A-Za-z0-9_]*)/g)];
  return matches.map((match) => match[1]);
}

function countClassNames(text) {
  return (text.match(/className=/g) ?? []).length;
}

function countJsxTags(text) {
  return (text.match(/<[A-Z][A-Za-z0-9_]*|<[a-z][a-z0-9-]*/g) ?? []).length;
}

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  return `${(bytes / 1024).toFixed(2)} KB`;
}

const files = scanDirs.flatMap(walk).sort();

const inventory = files.map((file) => {
  const full = path.join(root, file);
  const text = fs.readFileSync(full, "utf8");
  const bytes = Buffer.byteLength(text);
  const lineCount = text.split(/\r?\n/).length;
  const exports = detectExports(text);
  const classNameCount = countClassNames(text);
  const jsxTagCount = countJsxTags(text);
  const isCompositionLayer = /<SiteHeader|<InfoFooter|<Home[A-Z]|<Measurements[A-Z]|<Materials[A-Z]|<Assembly[A-Z]/.test(text)
    && classNameCount <= 3
    && lineCount <= 90;

  const flags = [];
  if (lineCount > maxSoftLines) flags.push("large-lines");
  if (bytes > maxSoftBytes) flags.push("large-bytes");
  if (classNameCount > 35) flags.push("many-classNames");
  if (jsxTagCount > 90) flags.push("many-jsx-tags");

  return {
    file,
    bytes,
    size: formatBytes(bytes),
    lineCount,
    exports,
    classNameCount,
    jsxTagCount,
    isCompositionLayer,
    flags,
  };
});

const totalBytes = inventory.reduce((sum, item) => sum + item.bytes, 0);
const flagged = inventory.filter((item) => item.flags.length);

const byDir = new Map();
for (const item of inventory) {
  const dir = path.dirname(item.file);
  const current = byDir.get(dir) ?? { count: 0, bytes: 0 };
  current.count += 1;
  current.bytes += item.bytes;
  byDir.set(dir, current);
}

const reportLines = [
  "# React component inventory report",
  "",
  "Generated by `npm run report:react-components`.",
  "",
  "## Summary",
  "",
  `- Scanned TSX files: ${inventory.length}`,
  `- Total TSX size: ${formatBytes(totalBytes)} (${totalBytes} bytes)`,
  `- Flagged candidates: ${flagged.length}`,
  "",
  "## By directory",
  "",
  "| Directory | Components | Size |",
  "|---|---:|---:|",
  ...[...byDir.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([dir, data]) => `| ${dir} | ${data.count} | ${formatBytes(data.bytes)} |`),
  "",
  "## Components",
  "",
  "| File | Size | Lines | Exports | className | JSX tags | Flags |",
  "|---|---:|---:|---|---:|---:|---|",
  ...inventory.map((item) => `| ${item.file} | ${item.size} | ${item.lineCount} | ${item.exports.join(", ") || "—"} | ${item.classNameCount} | ${item.jsxTagCount} | ${item.flags.join(", ") || "—"} |`),
  "",
  "## Flagged candidates",
  "",
  flagged.length
    ? flagged.map((item) => `- \`${item.file}\` — ${item.flags.join(", ")} (${item.lineCount} lines, ${item.size})`).join("\n")
    : "No candidates above soft thresholds.",
  "",
  "## Notes",
  "",
  "- This report does not change files.",
  "- Flags are soft indicators, not automatic refactor instructions.",
  "- A component can be intentionally large when it owns a unique section layout.",
];

const outputDir = path.join(root, "docs/audit");
fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(path.join(outputDir, "react-component-inventory-report.md"), reportLines.join("\n"), "utf8");

console.log("React component inventory complete");
console.log(`Scanned TSX files: ${inventory.length}`);
console.log(`Total TSX size: ${formatBytes(totalBytes)}`);
console.log(`Flagged candidates: ${flagged.length}`);
for (const item of flagged) {
  console.log(`${item.file}: ${item.flags.join(", ")} (${item.lineCount} lines, ${item.size})`);
}
